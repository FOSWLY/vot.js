import { normalizeLang } from "@vot.js/shared/utils/utils";
import { VideoDataSubtitle } from "@vot.js/core/types/client";

import { BaseHelper } from "./base";
import { MinimalVideoData } from "../types/client";

export default class XHamsterHelper extends BaseHelper {
  SUBTITLE_SOURCE = "xhamster";
  SUBTITLE_FORMAT: VideoDataSubtitle["format"] = "vtt";

  async getVideoData(videoId: string): Promise<MinimalVideoData | undefined> {
    const baseData: MinimalVideoData | undefined = this.returnBaseData(videoId);
    if (!baseData) {
      return undefined;
    }

    const fallbackSource = document.querySelector<HTMLLinkElement>(
      ".player-container__no-player",
    )?.href;
    const isMp4Video =
      fallbackSource &&
      fallbackSource.includes("xhcdn.com") &&
      fallbackSource.endsWith(".mp4");

    const autoSubs = this.video?.querySelectorAll<HTMLTrackElement>(
      'track[kind="metadata"]',
    );

    if (isMp4Video) {
      baseData.translationHelp = [
        {
          target: "video_file_url",
          targetUrl: fallbackSource,
        },
      ];
    }

    if (autoSubs?.length) {
      baseData.subtitles = Array.from(autoSubs)
        .filter((track) => track.src.includes(".vtt"))
        .map((track) => ({
          format: this.SUBTITLE_FORMAT,
          source: this.SUBTITLE_SOURCE,
          isAutoGenerated:
            track.label.includes("(") && track.label.endsWith(")"),
          language: normalizeLang(track.srclang),
          url: track.src,
        }));
    }

    return baseData;
  }

  async getVideoId(url: URL) {
    return /\/(videos\/[^/]+-[\dA-Za-z]+)\/?$/.exec(url.pathname)?.[1];
  }
}
